    pauseAllVideosGlobally() {
        // Pause ALL videos in the entire document - most comprehensive approach
        const allVideosInDocument = document.querySelectorAll('video');
        allVideosInDocument.forEach(video => {
            video.pause();
            video.muted = true; // Mute all videos to prevent background audio
            // Reset time for non-active videos
            if (!video.closest('.video-item.active')) {
                video.currentTime = 0;
            }
        });
        this.isPlaying = false;
        this.stopProgressUpdate();
    }    togglePlayPause() {
        // First pause all other videos to ensure only one plays
        this.pauseAllVideosGlobally();
        
        const currentVideo = this.container.querySelector('.video-item.active video');
        if (!currentVideo) return;

        if (this.isPlaying) {
            this.pauseCurrentVideo();
        } else {
            // Enable audio when user interacts and play only this video
            currentVideo.muted = false;
            currentVideo.volume = 0.8;
            
            const playPromise = currentVideo.play();
            if (playPromise !== undefined) {
                playPromise.then(() => {
                    this.isPlaying = true;
                    this.updatePlayPauseButton();
                    this.startProgressUpdate();
                }).catch(console.error);
            }
        }

        // Show play/pause button briefly
        const playPauseBtn = this.container.querySelector('.video-item.active .play-pause-btn');
        playPauseBtn.classList.add('show');
        setTimeout(() => {
            playPauseBtn.classList.remove('show');
        }, 500);
    }

    updatePlayPauseButton() {
        const playPauseBtn = this.container.querySelector('.video-item.active .play-pause-btn i');
        if (playPauseBtn) {
            playPauseBtn.className = this.isPlaying ? 'fas fa-pause' : 'fas fa-play';
        }
    }

    startProgressUpdate() {
        this.stopProgressUpdate();
        
        this.progressInterval = setInterval(() => {
            const currentVideo = this.container.querySelector('.video-item.active video');
            const progressFill = this.container.querySelector('.video-item.active .progress-fill');
            
            if (currentVideo && progressFill && currentVideo.duration) {
                const progress = (currentVideo.currentTime / currentVideo.duration) * 100;
                progressFill.style.height = `${progress}%`;                // Auto-play next video when current ends
                if (currentVideo.currentTime >= currentVideo.duration - 0.1) {
                    if (this.currentIndex < this.videos.length - 1) {
                        this.goToNext();
                    } else {
                        // Loop back to first video
                        this.pauseAllVideosGlobally();
                        this.currentIndex = 0;
                        this.loadVideo(0);
                        this.preloadAdjacentVideos(0);
                        this.updateVideoPositions();
                        setTimeout(() => {
                            this.playCurrentVideo();
                        }, 100);
                    }
                }
            }
        }, 100);
    }

    stopProgressUpdate() {
        if (this.progressInterval) {
            clearInterval(this.progressInterval);
            this.progressInterval = null;
        }
    }

