document.addEventListener('play', (e) => {
    if (e.target.tagName === 'VIDEO') {
        // When any video starts playing, pause all other videos
        const allVideos = document.querySelectorAll('video');
        allVideos.forEach(video => {
            if (video !== e.target) {
                video.pause();
                video.muted = true;
            }
        });
    }
}, true);
